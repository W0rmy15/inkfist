function ease(u) {
  return 1 - (1 - u) * (1 - u);
}

function lerpJoint(a, b, u) {
  return [a[0] + (b[0] - a[0]) * u, a[1] + (b[1] - a[1]) * u];
}

function lerpPose(a, b, u) {
  const out = {};
  for (const key of Object.keys(a)) out[key] = lerpJoint(a[key], b[key] || a[key], u);
  return out;
}

export function samplePose(name, frame) {
  const keys = POSES[name] || POSES.idle;
  const loop = LOOP[name];
  let f = frame;
  if (loop) f = ((frame % loop) + loop) % loop;
  let prev = keys[0];
  let next = keys[keys.length - 1];
  for (let i = 0; i < keys.length; i++) {
    if (keys[i].t <= f) prev = keys[i];
    if (keys[i].t >= f) {
      next = keys[i];
      break;
    }
  }
  if (next.snap) return f >= next.t ? next.j : prev.j;
  if (prev === next || next.t === prev.t) return prev.j;
  const u = ease((f - prev.t) / (next.t - prev.t));
  return lerpPose(prev.j, next.j, u);
}

function spin(p, a) {
  const c = Math.cos(a);
  const s = Math.sin(a);
  return [p[0] * c - p[1] * s, p[0] * s + p[1] * c];
}

export function poseOf(f) {
  let name = "idle";
  let frame = f.stateFrame;
  let rot = 0;
  if (f.state === "throw") {
    name = "throw";
    frame = f.moveFrame;
  } else if (f.state === "thrown") {
    name = "tumble";
    frame = f.stateFrame;
    rot = 1.15;
  } else if (f.move && POSES[f.move]) {
    name = f.move;
    frame = f.moveFrame;
  } else if ((f.state === "hitstun" || f.state === "parry_stun") && f.hitstop > 0) {
    name = f.react === "heavy" || f.react === "super" || f.react === "special" ? "hurtbig" : "hurt";
    frame = 0;
  } else if (f.state === "tumble" || ((f.state === "hitstun") && (f.airborne || f.y > 0))) {
    name = "tumble";
    frame = f.stateFrame;
    rot = [0.5, 1.55, 2.7, 4.05][Math.floor(f.stateFrame / 4) % 4];
  } else if (f.state === "hitstun" || f.state === "parry_stun") {
    name = "hurt";
  } else if (f.state === "ko") {
    name = "ko";
  } else if (f.state === "knockdown") {
    name = "down";
  } else if (f.state === "win") {
    name = "win";
  } else if (f.state === "parry") {
    name = "parry";
  } else if (f.state === "blockstun" || f.state === "block") {
    name = f.crouch ? "crouchblock" : "block";
  } else if (f.state === "crouch" || f.state === "jumpsquat" || f.state === "landlag") {
    name = "crouch";
  } else if (f.state === "dash") {
    name = f.dashDir < 0 ? "backdash" : "dash";
  } else if (f.dashTimer > 0 && (f.y > 0 || f.airborne)) {
    name = "airdash";
  } else if (f.state === "walk") {
    name = "walk";
  } else if (f.state === "air" || f.y > 0) {
    name = f.vy >= 0 ? "rise" : "fall";
  }
  let joints = samplePose(name, frame);
  if (rot) {
    const spun = {};
    for (const key of Object.keys(joints)) {
      spun[key] = key === "hip" ? joints[key] : spin(joints[key], rot);
    }
    joints = spun;
  }
  return { name, frame, rot, joints };
}
